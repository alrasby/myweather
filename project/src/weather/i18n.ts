export type CopyKey = keyof typeof ar;

const tables: Record<Lang, Record<CopyKey, string>> = { ar, en };

export function t(lang: Lang, key: CopyKey): string {
  if (key === "app") return textBase() === "ar" || lang === "ar" ? "طقسي" : "MyWeather";
  if (key === "appEn") return textBase() === "ar" || lang === "ar" ? "MyWeather" : "طقسي";
  const base = textBase();
  if (base !== "ar" && base !== "en") {
    const hit = worldLine(base, key);
    if (hit) return hit;
  }
  return tables[lang][key];
}

export function weatherKey(code: number): CopyKey {
  if (code === 0) return "wClear";
  if (code === 1) return "wMainly";
  if (code === 2) return "wPartly";
  if (code === 3) return "wCloud";
  if (code === 45 || code === 48) return "wFog";
  if (code >= 51 && code <= 57) return "wDrizzle";
  if ((code >= 61 && code <= 67) || (code >= 80 && code <= 82)) {
    return code >= 80 ? "wShowers" : "wRain";
  }
  if ((code >= 71 && code <= 77) || code === 85 || code === 86) return "wSnow";
  if (code >= 95) return "wStorm";
  return "wCloud";
}

const MOON_KEYS = [
  "newMoon",
  "waxCrescent",
  "firstQuarter",
  "waxGibbous",
  "fullMoon",
  "wanGibbous",
  "lastQuarter",
  "wanCrescent",
] as const;

export function moonKey(frac: number): CopyKey {
  const i = Math.floor((((frac % 1) + 1) % 1) * 8) % 8;
  return MOON_KEYS[i] ?? "newMoon";
}

export function aqiKey(aqi: number | null): CopyKey {
  if (aqi == null) return "aqi";
  if (aqi <= 50) return "good";
  if (aqi <= 100) return "moderate";
  if (aqi <= 150) return "poor";
  return "veryPoor";
}
