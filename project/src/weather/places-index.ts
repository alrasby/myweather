function fold(value: string): string {
  return value
    .normalize("NFKC")
    .trim()
    .toLowerCase()
    .replace(/[\u064b-\u065f\u0670\u06d6-\u06ed\u0640\u200c\u200d\u200e\u200f\ufeff]/g, "")
    .replace(/[أإآٱٲ]/g, "ا")
    .replace(/[ىيئىیېے]/g, "ي")
    .replace(/[كکڪ]/g, "ك")
    .replace(/[ةهھہە]/g, "ه")
    .replace(/ؤ/g, "و")
    .replace(/\s+/g, "");
}

export function normalizePlaceQuery(query: string): string {
  return query
    .normalize("NFKC")
    .trim()
    .replace(/[\u064b-\u065f\u0670\u06d6-\u06ed\u0640\u200c\u200d\u200e\u200f\ufeff]/g, "")
    .replace(/[أإآٱٲ]/g, "ا")
    .replace(/[ىيئىیېے]/g, "ي")
    .replace(/[كکڪ]/g, "ك")
    .replace(/[ةهھہە]/g, "ه")
    .replace(/ؤ/g, "و")
    .replace(/\s+/g, " ");
}

export function searchLocal(query: string): Place[] {
  const q = fold(query);
  if (q.length < 2) return [];
  const ranked = SEEDS.map((row) => {
    const [en, ar, country, countryAr, lat, lon, pop] = row;
    const fields = [en, ar, country, countryAr].map(fold);
    const stem = q.length > 2 ? q.slice(0, -1) : "";
    let score = 0;
    for (const field of fields) {
      if (field === q) score = Math.max(score, 100);
      else if (field.startsWith(q)) score = Math.max(score, 80);
      else if (field.includes(q)) score = Math.max(score, 40);
      else if (stem && field.startsWith(stem) && field.length <= q.length && Math.abs(field.length - q.length) <= 1) score = Math.max(score, 70);
    }
    return { row, score, pop, lat, lon };
  })
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score || b.pop - a.pop);
  return ranked.slice(0, 8).map(({ row }) => {
    const [en, ar, country, countryAr, lat, lon] = row;
    return {
      id: `${lat.toFixed(2)},${lon.toFixed(2)}`,
      name: ar,
      nameEn: en,
      country: countryAr,
      countryEn: country,
      admin: "",
      lat,
      lon,
      primary: false,
    };
  });
}
